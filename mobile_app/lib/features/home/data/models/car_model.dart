class CarModel {
  final String name;
  final String brand;
  final String price;
  final String image;

  final String year;
  final String engine;
  final String mileage;
  final String transmission;
  final String description;


  CarModel({
    required this.name,
    required this.brand,
    required this.price,
    required this.image,

    required this.year,
    required this.engine,
    required this.mileage,
    required this.transmission,
    required this.description,
  });
}
